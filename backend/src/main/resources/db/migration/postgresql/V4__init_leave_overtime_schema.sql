-- Atria Flyway Migration V4 (PostgreSQL 16)
-- Phase 3b: Leave Types, Seniority Grant Rules, FIFO Balance Ledger & Tx Audit,
-- Statutory Overtime Rate/Cap Rules, Comp-Leave Grants & Request State Machine
