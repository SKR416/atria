-- 1. Leave type definitions with trilingual names and minimum unit rounding
CREATE TABLE att_leave_type (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                 VARCHAR(32)  NOT NULL,
    name                 JSONB        NOT NULL,
    min_unit_minutes     INT          NOT NULL DEFAULT 60,
    paid                 BOOLEAN      NOT NULL DEFAULT TRUE,
    balance_tracked      BOOLEAN      NOT NULL DEFAULT TRUE,
    attachment_required  BOOLEAN      NOT NULL DEFAULT FALSE,
    enabled              BOOLEAN      NOT NULL DEFAULT TRUE,
    sort_order           INT          NOT NULL DEFAULT 0,
    description          VARCHAR(255),
    version              BIGINT       NOT NULL DEFAULT 0,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by           BIGINT,
    updated_by           BIGINT,
    is_deleted           BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_att_leave_type_code UNIQUE (code)
);

-- 2. Seniority-based annual leave grant rules per calendar region (TW Art. 38 / JP Art. 39)
CREATE TABLE att_leave_grant_rule (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calendar_code       VARCHAR(16)  NOT NULL,
    leave_type_code     VARCHAR(32)  NOT NULL DEFAULT 'ANNUAL',
    grant_basis         VARCHAR(20)  NOT NULL DEFAULT 'ANNIVERSARY',
    min_tenure_months   INT          NOT NULL,
    max_tenure_months   INT,
    grant_days          INT          NOT NULL,
    grant_minutes       INT          NOT NULL,
    valid_months        INT          NOT NULL DEFAULT 12,
    note                VARCHAR(255),
    version             BIGINT       NOT NULL DEFAULT 0,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by          BIGINT,
    updated_by          BIGINT,
    is_deleted          BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_att_leave_grant_basis CHECK (grant_basis IN ('ANNIVERSARY', 'CALENDAR_YEAR'))
);

CREATE INDEX idx_att_leave_grant_rule_cal ON att_leave_grant_rule (calendar_code, min_tenure_months);

-- 3. Unified attendance request table (LEAVE, OVERTIME, PUNCH_CORRECTION)
CREATE TABLE att_request (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL REFERENCES iam_user (id),
    department_id       BIGINT       REFERENCES iam_department (id),
    calendar_code       VARCHAR(16)  NOT NULL,
    request_type        VARCHAR(32)  NOT NULL,
    status              VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    leave_type_code     VARCHAR(32),
    start_date          DATE         NOT NULL,
    end_date            DATE         NOT NULL,
    start_time          TIMESTAMP WITH TIME ZONE NOT NULL,
    end_time            TIMESTAMP WITH TIME ZONE NOT NULL,
    requested_minutes   INT          NOT NULL DEFAULT 0,
    weighted_minutes    INT          NOT NULL DEFAULT 0,
    overtime_comp_type  VARCHAR(20),
    comp_leave_mode     VARCHAR(24),
    reason              VARCHAR(500) NOT NULL,
    attachment_path     VARCHAR(255),
    warning_messages    VARCHAR(500),
    reviewed_by         BIGINT,
    reviewed_at         TIMESTAMP WITH TIME ZONE,
    review_comment      VARCHAR(500),
    revoked_by          BIGINT,
    revoked_at          TIMESTAMP WITH TIME ZONE,
    revoke_reason       VARCHAR(500),
    version             BIGINT       NOT NULL DEFAULT 0,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by          BIGINT,
    updated_by          BIGINT,
    is_deleted          BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_att_request_type CHECK (request_type IN ('LEAVE', 'OVERTIME', 'PUNCH_CORRECTION')),
    CONSTRAINT ck_att_request_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED', 'REVOKED')),
    CONSTRAINT ck_att_request_ot_comp CHECK (overtime_comp_type IS NULL OR overtime_comp_type IN ('PAY', 'COMP_LEAVE')),
    CONSTRAINT ck_att_request_comp_mode CHECK (comp_leave_mode IS NULL OR comp_leave_mode IN ('HOURS_1_TO_1', 'RATE_MULTIPLIED'))
);

CREATE INDEX idx_att_request_user_dates ON att_request (user_id, start_date, end_date);
CREATE INDEX idx_att_request_cal_status_dates ON att_request (calendar_code, status, start_date, end_date);

-- Add foreign key on existing att_punch_log.correction_request_id -> att_request(id) (ADR-0008 Decision 3)
ALTER TABLE att_punch_log
    ADD CONSTRAINT fk_att_punch_log_correction_request
    FOREIGN KEY (correction_request_id) REFERENCES att_request (id);

-- 4. Compensatory leave grant record storing original rate band breakdown JSON (no used_minutes column)
CREATE TABLE att_comp_leave_grant (
    id                                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                           BIGINT       NOT NULL REFERENCES iam_user (id),
    calendar_code                     VARCHAR(16)  NOT NULL,
    source_request_id                 BIGINT       NOT NULL REFERENCES att_request (id),
    work_date                         DATE         NOT NULL,
    day_type                          VARCHAR(32)  NOT NULL,
    comp_leave_mode                   VARCHAR(24)  NOT NULL,
    original_overtime_minutes         INT          NOT NULL,
    granted_minutes                   INT          NOT NULL,
    residual_payable_minutes          INT          NOT NULL DEFAULT 0,
    band_breakdown_json               JSONB        NOT NULL,
    granted_at                        TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at                        DATE         NOT NULL,
    expired_settled                   BOOLEAN      NOT NULL DEFAULT FALSE,
    expired_payable_weighted_minutes  INT          NOT NULL DEFAULT 0,
    version                           BIGINT       NOT NULL DEFAULT 0,
    created_at                        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at                        TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by                        BIGINT,
    updated_by                        BIGINT,
    is_deleted                        BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_att_comp_leave_grant_req UNIQUE (source_request_id),
    CONSTRAINT ck_att_comp_grant_mode CHECK (comp_leave_mode IN ('HOURS_1_TO_1', 'RATE_MULTIPLIED'))
);

CREATE INDEX idx_att_comp_leave_grant_user_exp ON att_comp_leave_grant (user_id, expires_at);

-- 5. Employee leave balance buckets (single source of truth for annual & comp-leave balances)
CREATE TABLE att_leave_balance (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                   BIGINT       NOT NULL REFERENCES iam_user (id),
    leave_type_code           VARCHAR(32)  NOT NULL,
    calendar_code             VARCHAR(16)  NOT NULL,
    grant_year                INT          NOT NULL,
    total_minutes             INT          NOT NULL,
    used_minutes              INT          NOT NULL DEFAULT 0,
    pending_minutes           INT          NOT NULL DEFAULT 0,
    valid_from                DATE         NOT NULL,
    valid_until               DATE         NOT NULL,
    source_comp_grant_id      BIGINT       REFERENCES att_comp_leave_grant (id),
    mandatory_target_minutes  INT          NOT NULL DEFAULT 0,
    note                      VARCHAR(255),
    version                   BIGINT       NOT NULL DEFAULT 0,
    created_at                TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at                TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by                BIGINT,
    updated_by                BIGINT,
    is_deleted                BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_att_leave_balance_user_type_valid ON att_leave_balance (user_id, leave_type_code, valid_until);
CREATE INDEX idx_att_leave_balance_comp_grant ON att_leave_balance (source_comp_grant_id);

-- 6. FIFO leave balance transaction ledger (enables 100% exact per-bucket restore on reject/cancel/revoke)
CREATE TABLE att_leave_balance_tx (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id       BIGINT       NOT NULL REFERENCES att_request (id),
    balance_id       BIGINT       NOT NULL REFERENCES att_leave_balance (id),
    user_id          BIGINT       NOT NULL REFERENCES iam_user (id),
    leave_type_code  VARCHAR(32)  NOT NULL,
    tx_type          VARCHAR(24)  NOT NULL,
    minutes          INT          NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_att_leave_balance_tx_type CHECK (
        tx_type IN ('FREEZE', 'COMMIT', 'RESTORE_PENDING', 'RESTORE_USED')
    )
);

CREATE INDEX idx_att_leave_balance_tx_req ON att_leave_balance_tx (request_id);
CREATE INDEX idx_att_leave_balance_tx_bal ON att_leave_balance_tx (balance_id);

-- 7. Regional overtime rate rules (TW 1.34/1.67/2.67/2.00 & JP 1.25/1.35/1.50/+0.25)
CREATE TABLE att_overtime_rate_rule (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calendar_code            VARCHAR(16)   NOT NULL,
    day_type                 VARCHAR(32)   NOT NULL,
    from_minute              INT           NOT NULL,
    to_minute                INT           NOT NULL,
    multiplier               NUMERIC(6,4)  NOT NULL,
    is_night_premium         BOOLEAN       NOT NULL DEFAULT FALSE,
    is_monthly_cumulative    BOOLEAN       NOT NULL DEFAULT FALSE,
    default_comp_leave_mode  VARCHAR(24)   NOT NULL DEFAULT 'RATE_MULTIPLIED',
    description              VARCHAR(255),
    version                  BIGINT        NOT NULL DEFAULT 0,
    created_at               TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at               TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by               BIGINT,
    updated_by               BIGINT,
    is_deleted               BOOLEAN       NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_att_ot_rate_rule_cal_day ON att_overtime_rate_rule (calendar_code, day_type, from_minute);

-- 8. Regional overtime cap rules with WARN / BLOCK enforcement
CREATE TABLE att_overtime_cap_rule (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calendar_code       VARCHAR(16)  NOT NULL,
    rule_code           VARCHAR(48)  NOT NULL,
    name                JSONB        NOT NULL,
    period_months       INT          NOT NULL DEFAULT 1,
    max_minutes         INT          NOT NULL,
    enforcement_action  VARCHAR(16)  NOT NULL,
    enabled             BOOLEAN      NOT NULL DEFAULT TRUE,
    description         VARCHAR(255),
    version             BIGINT       NOT NULL DEFAULT 0,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by          BIGINT,
    updated_by          BIGINT,
    is_deleted          BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_att_overtime_cap_rule_code UNIQUE (rule_code),
    CONSTRAINT ck_att_overtime_cap_action CHECK (enforcement_action IN ('WARN', 'BLOCK'))
);

