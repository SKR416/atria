-- 1. Bind departments to a regional calendar code (e.g. TW, JP)
ALTER TABLE iam_department
    ADD COLUMN calendar_code VARCHAR(16) NOT NULL DEFAULT 'TW';

-- 2. Multi-region work calendar with legal day types
CREATE TABLE att_work_calendar (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calendar_code     VARCHAR(16)  NOT NULL,
    work_date         DATE         NOT NULL,
    day_type          VARCHAR(32)  NOT NULL,
    work_start_time   TIME         NOT NULL DEFAULT '09:00:00',
    work_end_time     TIME         NOT NULL DEFAULT '18:00:00',
    break_start_time  TIME         NOT NULL DEFAULT '12:00:00',
    break_end_time    TIME         NOT NULL DEFAULT '13:00:00',
    holiday_name      JSONB,
    note              VARCHAR(255),
    version           BIGINT       NOT NULL DEFAULT 0,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by        BIGINT,
    updated_by        BIGINT,
    is_deleted        BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_att_work_calendar_code_date UNIQUE (calendar_code, work_date),
    CONSTRAINT ck_att_work_calendar_day_type CHECK (
        day_type IN ('WORKDAY', 'MAKEUP_WORKDAY', 'REST_DAY', 'STATUTORY_REST_DAY', 'NATIONAL_HOLIDAY')
    )
);

CREATE INDEX idx_att_work_calendar_code_date ON att_work_calendar (calendar_code, work_date);

-- 3. Configurable punch & cross-midnight cutoff rules per calendar region
CREATE TABLE att_punch_rule (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calendar_code               VARCHAR(16) NOT NULL,
    late_grace_minutes          INT         NOT NULL DEFAULT 5,
    early_leave_grace_minutes   INT         NOT NULL DEFAULT 0,
    clock_in_rounding_minutes   INT         NOT NULL DEFAULT 1,
    clock_out_rounding_minutes  INT         NOT NULL DEFAULT 1,
    day_cutoff_hour             INT         NOT NULL DEFAULT 4,
    min_punch_interval_seconds  INT         NOT NULL DEFAULT 60,
    max_retroactive_days        INT         NOT NULL DEFAULT 14,
    auto_monthly_close_day      INT         NOT NULL DEFAULT 5,
    version                     BIGINT      NOT NULL DEFAULT 0,
    created_at                  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at                  TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by                  BIGINT,
    updated_by                  BIGINT,
    is_deleted                  BOOLEAN     NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_att_punch_rule_calendar UNIQUE (calendar_code)
);

-- 4. Append-only immutable raw punch log (ADR-0008 Decision 1)
CREATE TABLE att_punch_log (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                BIGINT      NOT NULL REFERENCES iam_user (id),
    department_id          BIGINT      REFERENCES iam_department (id),
    work_date              DATE        NOT NULL,
    raw_punch_time         TIMESTAMP WITH TIME ZONE NOT NULL,
    client_ip              VARCHAR(64) NOT NULL,
    source                 VARCHAR(20) NOT NULL,
    bot_client_id          VARCHAR(64),
    correction_request_id  BIGINT,
    note                   VARCHAR(255),
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_att_punch_log_source CHECK (source IN ('WEB', 'BOT', 'CORRECTION'))
);

CREATE INDEX idx_att_punch_log_user_date ON att_punch_log (user_id, work_date);
CREATE INDEX idx_att_punch_log_user_time ON att_punch_log (user_id, raw_punch_time);

-- Enforce strict append-only immutability on att_punch_log at the PostgreSQL database layer
CREATE OR REPLACE FUNCTION fn_prevent_att_punch_log_mutation()
RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'att_punch_log is strictly append-only and immutable (labor inspection audit ledger)';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_att_punch_log_immutable
BEFORE UPDATE OR DELETE ON att_punch_log
FOR EACH ROW EXECUTE FUNCTION fn_prevent_att_punch_log_mutation();

-- 5. Derived daily attendance record per user & logical work date (ADR-0008 Decision 1)
CREATE TABLE att_daily_record (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id               BIGINT      NOT NULL REFERENCES iam_user (id),
    department_id         BIGINT      REFERENCES iam_department (id),
    calendar_code         VARCHAR(16) NOT NULL,
    work_date             DATE        NOT NULL,
    day_type              VARCHAR(32) NOT NULL,
    scheduled_start_time  TIME,
    scheduled_end_time    TIME,
    first_raw_clock_in    TIMESTAMP WITH TIME ZONE,
    last_raw_clock_out    TIMESTAMP WITH TIME ZONE,
    effective_clock_in    TIMESTAMP WITH TIME ZONE,
    effective_clock_out   TIMESTAMP WITH TIME ZONE,
    worked_minutes        INT         NOT NULL DEFAULT 0,
    late_minutes          INT         NOT NULL DEFAULT 0,
    early_leave_minutes   INT         NOT NULL DEFAULT 0,
    leave_minutes         INT         NOT NULL DEFAULT 0,
    overtime_minutes      INT         NOT NULL DEFAULT 0,
    status                VARCHAR(32) NOT NULL,
    punch_count           INT         NOT NULL DEFAULT 0,
    settled               BOOLEAN     NOT NULL DEFAULT FALSE,
    note                  VARCHAR(500),
    version               BIGINT      NOT NULL DEFAULT 0,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by            BIGINT,
    updated_by            BIGINT,
    is_deleted            BOOLEAN     NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_att_daily_record_user_date UNIQUE (user_id, work_date),
    CONSTRAINT ck_att_daily_record_status CHECK (
        status IN ('NORMAL', 'LATE', 'EARLY_LEAVE', 'MISSING_PUNCH', 'ON_LEAVE', 'ABSENT', 'HOLIDAY')
    )
);

CREATE INDEX idx_att_daily_record_dept_date ON att_daily_record (department_id, work_date);
CREATE INDEX idx_att_daily_record_work_date ON att_daily_record (work_date);

-- 6. Monthly closing lock per calendar region & YYYY-MM (ADR-0003, ADR-0008 Decision 7)
CREATE TABLE att_monthly_close (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calendar_code       VARCHAR(16) NOT NULL,
    year_month          VARCHAR(7)  NOT NULL,
    status              VARCHAR(20) NOT NULL DEFAULT 'CLOSED',
    closed_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    closed_by           BIGINT,
    closed_by_username  VARCHAR(64),
    reopened_at         TIMESTAMP WITH TIME ZONE,
    reopened_by         BIGINT,
    note                VARCHAR(500),
    version             BIGINT      NOT NULL DEFAULT 0,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by          BIGINT,
    updated_by          BIGINT,
    is_deleted          BOOLEAN     NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_att_monthly_close_cal_ym UNIQUE (calendar_code, year_month),
    CONSTRAINT ck_att_monthly_close_status CHECK (status IN ('CLOSED', 'REOPENED'))
);

