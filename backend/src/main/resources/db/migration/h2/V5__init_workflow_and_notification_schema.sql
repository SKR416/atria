-- ============================================================================
-- Atria Flyway Migration V5 (H2 Dialect)
-- Phase 4: Dynamic Form Templates, Structured-Condition Multi-Level Workflow,
-- Deputy Delegation, In-App / Email Notification Foundation & Monthly Digest
-- (ADR-0005, ADR-0008 Decisions 8, 9, 10)
-- ============================================================================

-- 1. Dynamic form templates with JSON schema and version snapshots (ADR-0005 Decision 1)
CREATE TABLE wf_form_template (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             VARCHAR(48)  NOT NULL,
    name             JSON         NOT NULL,
    category         VARCHAR(24)  NOT NULL DEFAULT 'GENERAL',
    current_version  INT          NOT NULL DEFAULT 1,
    schema_json      JSON         NOT NULL,
    enabled          BOOLEAN      NOT NULL DEFAULT TRUE,
    description      VARCHAR(255),
    version          BIGINT       NOT NULL DEFAULT 0,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by       BIGINT,
    updated_by       BIGINT,
    is_deleted       BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_wf_form_template_code UNIQUE (code),
    CONSTRAINT ck_wf_form_template_category CHECK (category IN ('ATTENDANCE', 'GENERAL'))
);

-- 2. Approval workflow definitions (ADR-0005 Decision 2)
CREATE TABLE wf_flow_definition (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                VARCHAR(48)  NOT NULL,
    name                JSON         NOT NULL,
    target_type         VARCHAR(32)  NOT NULL,
    form_template_code  VARCHAR(48),
    enabled             BOOLEAN      NOT NULL DEFAULT TRUE,
    description         VARCHAR(255),
    version             BIGINT       NOT NULL DEFAULT 0,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by          BIGINT,
    updated_by          BIGINT,
    is_deleted          BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_wf_flow_def_code UNIQUE (code),
    CONSTRAINT ck_wf_flow_target_type CHECK (
        target_type IN ('ATT_LEAVE', 'ATT_OVERTIME', 'ATT_PUNCH_CORRECTION', 'DYNAMIC_FORM')
    )
);

CREATE INDEX idx_wf_flow_def_target ON wf_flow_definition (target_type, form_template_code);

-- 3. Ordered approval steps per workflow definition
CREATE TABLE wf_flow_node (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flow_definition_id       BIGINT       NOT NULL REFERENCES wf_flow_definition (id),
    step_order               INT          NOT NULL,
    node_code                VARCHAR(48)  NOT NULL,
    name                     JSON         NOT NULL,
    approver_strategy        VARCHAR(32)  NOT NULL,
    role_code                VARCHAR(64),
    self_approval_auto_skip  BOOLEAN      NOT NULL DEFAULT TRUE,
    allow_deputy             BOOLEAN      NOT NULL DEFAULT TRUE,
    version                  BIGINT       NOT NULL DEFAULT 0,
    created_at               TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at               TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by               BIGINT,
    updated_by               BIGINT,
    is_deleted               BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_wf_node_strategy CHECK (
        approver_strategy IN ('DIRECT_LEADER', 'PARENT_LEADER', 'SPECIFIC_ROLE')
    )
);

CREATE INDEX idx_wf_flow_node_def_step ON wf_flow_node (flow_definition_id, step_order);

-- 4. Structured node activation conditions evaluated in pure Java (no SpEL, ADR-0008 Decision 10)
CREATE TABLE wf_flow_node_condition (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flow_node_id    BIGINT       NOT NULL REFERENCES wf_flow_node (id),
    logical_group   INT          NOT NULL DEFAULT 1,
    field_key       VARCHAR(64)  NOT NULL,
    operator        VARCHAR(16)  NOT NULL,
    expected_value  VARCHAR(255) NOT NULL,
    version         BIGINT       NOT NULL DEFAULT 0,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by      BIGINT,
    updated_by      BIGINT,
    is_deleted      BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_wf_cond_operator CHECK (
        operator IN ('EQ', 'NE', 'GT', 'GTE', 'LT', 'LTE', 'IN')
    )
);

CREATE INDEX idx_wf_node_cond_node ON wf_flow_node_condition (flow_node_id, logical_group);

-- 5. Workflow instances with optimistic locking, schema snapshot, and Return-to-Draft diff (ADR-0005 Decision 3)
CREATE TABLE wf_instance (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instance_no              VARCHAR(48)   NOT NULL,
    flow_definition_id       BIGINT        NOT NULL REFERENCES wf_flow_definition (id),
    target_type              VARCHAR(32)   NOT NULL,
    att_request_id           BIGINT        REFERENCES att_request (id),
    form_template_code       VARCHAR(48),
    form_version             INT,
    schema_snapshot_json     JSON,
    applicant_id             BIGINT        NOT NULL REFERENCES iam_user (id),
    department_id            BIGINT        REFERENCES iam_department (id),
    title                    VARCHAR(200)  NOT NULL,
    status                   VARCHAR(24)   NOT NULL DEFAULT 'PENDING',
    current_step_order       INT,
    current_approver_id      BIGINT        REFERENCES iam_user (id),
    form_data_json           JSON          NOT NULL,
    previous_form_data_json  JSON,
    diff_json                JSON,
    submission_count         INT           NOT NULL DEFAULT 1,
    submitted_at             TIMESTAMP WITH TIME ZONE,
    completed_at             TIMESTAMP WITH TIME ZONE,
    version                  BIGINT        NOT NULL DEFAULT 0,
    created_at               TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at               TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by               BIGINT,
    updated_by               BIGINT,
    is_deleted               BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_wf_instance_no UNIQUE (instance_no),
    CONSTRAINT uq_wf_instance_att_req UNIQUE (att_request_id),
    CONSTRAINT ck_wf_instance_status CHECK (
        status IN ('DRAFT', 'PENDING', 'APPROVED', 'REJECTED', 'CANCELLED', 'REVOKED')
    )
);

CREATE INDEX idx_wf_instance_applicant ON wf_instance (applicant_id, status);
CREATE INDEX idx_wf_instance_approver ON wf_instance (current_approver_id, status);
CREATE INDEX idx_wf_instance_dept ON wf_instance (department_id, status);

-- 6. Immutable workflow task audit trail (records deputy delegator & HR forced reassignments)
CREATE TABLE wf_task_log (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instance_id            BIGINT        NOT NULL REFERENCES wf_instance (id),
    step_order             INT           NOT NULL DEFAULT 0,
    node_name              JSON          NOT NULL,
    action                 VARCHAR(32)   NOT NULL,
    assigned_approver_id   BIGINT        REFERENCES iam_user (id),
    actor_user_id          BIGINT        NOT NULL REFERENCES iam_user (id),
    delegator_user_id      BIGINT        REFERENCES iam_user (id),
    reassigned_to_user_id  BIGINT        REFERENCES iam_user (id),
    comment                VARCHAR(500),
    acted_at               TIMESTAMP WITH TIME ZONE NOT NULL,
    version                BIGINT        NOT NULL DEFAULT 0,
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by             BIGINT,
    updated_by             BIGINT,
    is_deleted             BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_wf_task_log_action CHECK (
        action IN ('SUBMIT', 'RESUBMIT', 'APPROVE', 'REJECT', 'RETURN_TO_DRAFT', 'CANCEL', 'REVOKE', 'REASSIGN', 'AUTO_SKIP')
    )
);

CREATE INDEX idx_wf_task_log_instance ON wf_task_log (instance_id, acted_at);
CREATE INDEX idx_wf_task_log_actor ON wf_task_log (actor_user_id, acted_at);

-- 7. Deputy delegation periods (ADR-0005 Decision 3)
CREATE TABLE wf_deputy (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delegator_user_id  BIGINT        NOT NULL REFERENCES iam_user (id),
    deputy_user_id     BIGINT        NOT NULL REFERENCES iam_user (id),
    start_date         DATE          NOT NULL,
    end_date           DATE          NOT NULL,
    enabled            BOOLEAN       NOT NULL DEFAULT TRUE,
    reason             VARCHAR(255),
    version            BIGINT        NOT NULL DEFAULT 0,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by         BIGINT,
    updated_by         BIGINT,
    is_deleted         BOOLEAN       NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_wf_deputy_delegator_dates ON wf_deputy (delegator_user_id, enabled, start_date, end_date);
CREATE INDEX idx_wf_deputy_deputy_dates ON wf_deputy (deputy_user_id, enabled, start_date, end_date);

-- 8. In-app & email notification records (ADR-0008 Decision 10)
CREATE TABLE ntf_notification (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_id  BIGINT        NOT NULL REFERENCES iam_user (id),
    category           VARCHAR(32)   NOT NULL,
    title              JSON          NOT NULL,
    content            JSON          NOT NULL,
    reference_type     VARCHAR(32),
    reference_id       BIGINT,
    is_read            BOOLEAN       NOT NULL DEFAULT FALSE,
    read_at            TIMESTAMP WITH TIME ZONE,
    email_sent         BOOLEAN       NOT NULL DEFAULT FALSE,
    version            BIGINT        NOT NULL DEFAULT 0,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by         BIGINT,
    updated_by         BIGINT,
    is_deleted         BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_ntf_category CHECK (category IN ('WORKFLOW', 'LEAVE_DIGEST', 'SYSTEM'))
);

CREATE INDEX idx_ntf_recipient_read ON ntf_notification (recipient_user_id, is_read, created_at DESC);

-- 9. Idempotent monthly leave balance digest delivery log (ADR-0008 Decision 8)
CREATE TABLE ntf_digest_log (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT       NOT NULL REFERENCES iam_user (id),
    period_year_month  VARCHAR(7)   NOT NULL,
    calendar_code      VARCHAR(16)  NOT NULL,
    notification_id    BIGINT       REFERENCES ntf_notification (id),
    delivered_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    summary_json       JSON         NOT NULL,
    version            BIGINT       NOT NULL DEFAULT 0,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by         BIGINT,
    updated_by         BIGINT,
    is_deleted         BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_ntf_digest_user_period UNIQUE (user_id, period_year_month)
);

