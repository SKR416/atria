-- Phase 1: IAM schema (PostgreSQL 16). The H2 variant under db/migration/h2 must stay logically identical.
-- H2 variant: JSON instead of JSONB; soft-delete uniqueness is enforced in the service layer (no partial indexes).

CREATE TABLE iam_department (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id     BIGINT REFERENCES iam_department (id),
    tree_path     VARCHAR(512) NOT NULL,
    code          VARCHAR(64)  NOT NULL,
    name          JSON        NOT NULL,
    leader_id     BIGINT,
    timezone      VARCHAR(64)  NOT NULL DEFAULT 'Asia/Taipei',
    sort_order    INT          NOT NULL DEFAULT 0,
    version       BIGINT       NOT NULL DEFAULT 0,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by    BIGINT,
    updated_by    BIGINT,
    is_deleted    BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE iam_user (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username               VARCHAR(64)  NOT NULL,
    email                  VARCHAR(255),
    password_hash          VARCHAR(255) NOT NULL,
    display_name           VARCHAR(100) NOT NULL,
    department_id          BIGINT REFERENCES iam_department (id),
    locale                 VARCHAR(10)  NOT NULL DEFAULT 'zh-TW',
    enabled                BOOLEAN      NOT NULL DEFAULT TRUE,
    failed_login_attempts  INT          NOT NULL DEFAULT 0,
    locked_until           TIMESTAMP WITH TIME ZONE,
    must_change_password   BOOLEAN      NOT NULL DEFAULT FALSE,
    token_version          BIGINT       NOT NULL DEFAULT 0,
    last_login_at          TIMESTAMP WITH TIME ZONE,
    password_changed_at    TIMESTAMP WITH TIME ZONE,
    version                BIGINT       NOT NULL DEFAULT 0,
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by             BIGINT,
    updated_by             BIGINT,
    is_deleted             BOOLEAN      NOT NULL DEFAULT FALSE
);

ALTER TABLE iam_department
    ADD CONSTRAINT fk_iam_department_leader FOREIGN KEY (leader_id) REFERENCES iam_user (id);

CREATE TABLE iam_role (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(64)  NOT NULL,
    name        JSON        NOT NULL,
    data_scope  VARCHAR(20)  NOT NULL,
    built_in    BOOLEAN      NOT NULL DEFAULT FALSE,
    version     BIGINT       NOT NULL DEFAULT 0,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by  BIGINT,
    updated_by  BIGINT,
    is_deleted  BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_iam_role_data_scope CHECK (data_scope IN ('ALL', 'DEPT_AND_SUB', 'DEPT_ONLY', 'SELF_ONLY'))
);

CREATE TABLE iam_permission (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code    VARCHAR(100) NOT NULL,
    module  VARCHAR(32)  NOT NULL,
    name    JSON        NOT NULL,
    CONSTRAINT uq_iam_permission_code UNIQUE (code)
);

CREATE TABLE iam_user_role (
    user_id  BIGINT NOT NULL REFERENCES iam_user (id),
    role_id  BIGINT NOT NULL REFERENCES iam_role (id),
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE iam_role_permission (
    role_id        BIGINT NOT NULL REFERENCES iam_role (id),
    permission_id  BIGINT NOT NULL REFERENCES iam_permission (id),
    PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE iam_audit_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id        BIGINT,
    actor_username  VARCHAR(64),
    action          VARCHAR(64)  NOT NULL,
    target_type     VARCHAR(32),
    target_id       VARCHAR(64),
    detail          VARCHAR(1000),
    client_ip       VARCHAR(64),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_iam_department_parent ON iam_department (parent_id);
CREATE INDEX idx_iam_department_tree_path ON iam_department (tree_path);
CREATE INDEX idx_iam_user_department ON iam_user (department_id);
CREATE INDEX idx_iam_audit_log_created ON iam_audit_log (created_at);
CREATE INDEX idx_iam_audit_log_actor ON iam_audit_log (actor_id);

-- Soft-delete aware uniqueness (ADR-0004): archived rows never block re-hires / code reuse.
CREATE INDEX uq_iam_user_username ON iam_user (username);
CREATE INDEX uq_iam_user_email ON iam_user (email);
CREATE INDEX uq_iam_department_code ON iam_department (code);
CREATE INDEX uq_iam_role_code ON iam_role (code);

